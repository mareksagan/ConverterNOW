      PROPERTYX.force: Force(
        significantFigures: significantFigures,
        removeTrailingZeros: removeTrailingZeros,
        name: PROPERTYX.force,
      ),
      PROPERTYX.fuelConsumption: FuelConsumption(
        significantFigures: significantFigures,
