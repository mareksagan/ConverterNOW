final propertiesMapProvider = Provider<Map<PROPERTYX, Property>>(
  (ref) {
    final removeTrailingZeros = ref.watch(removeTrailingZerosProvider).value ?? true;
    final significantFigures = ref.watch(significantFiguresProvider).value ?? 10;
    final exchangeRates = ref
        .watch(CurrenciesNotifier.provider)
        .when(
          data:
              (currencies) => Map<String, double>.fromEntries(
                currencies.exchangeRates.entries.where(
                  (e) => _currenciesSymbols.containsKey(e.key),
                ),
              ),
          error: (_, trace) => Currencies.defaultExchangeRates,
          loading: () => Currencies.defaultExchangeRates,
        );
    return {
      PROPERTYX.length: Length(
        significantFigures: significantFigures,
        removeTrailingZeros: removeTrailingZeros,
        name: PROPERTYX.length,
      ),
      PROPERTYX.area: Area(
        significantFigures: significantFigures,
        removeTrailingZeros: removeTrailingZeros,
        name: PROPERTYX.area,
      ),
      PROPERTYX.density: Density(
        significantFigures: significantFigures,
        removeTrailingZeros: removeTrailingZeros,
        name: PROPERTYX.density,
      ),
      PROPERTYX.volume: Volume(
        significantFigures: significantFigures,
        removeTrailingZeros: removeTrailingZeros,
        name: PROPERTYX.volume,
      ),
      PROPERTYX.currencies: SimpleCustomProperty(
        exchangeRates,
        mapSymbols: _currenciesSymbols,
        significantFigures: significantFigures,
        removeTrailingZeros: removeTrailingZeros,
        name: PROPERTYX.currencies,
      ),
      PROPERTYX.time: Time(
        significantFigures: significantFigures,
        removeTrailingZeros: removeTrailingZeros,
        name: PROPERTYX.time,
      ),
      PROPERTYX.temperature: Temperature(
        significantFigures: significantFigures,
        removeTrailingZeros: removeTrailingZeros,
        name: PROPERTYX.temperature,
      ),
      PROPERTYX.speed: Speed(
        significantFigures: significantFigures,
        removeTrailingZeros: removeTrailingZeros,
        name: PROPERTYX.speed,
      ),
      PROPERTYX.mass: Mass(
